assert.ok(childClamped.x+childClamped.w<=table.x+table.w+1e-6);
assert.ok(childClamped.y+childClamped.h<=table.y+table.h+1e-6);
assert.deepEqual(importLayout(exportLayout(shifted),h.props,h.cols,h.rows),shifted);
assert.throws(()=>importLayout(exportLayout(h.props.map(p=>p.id===laptop.id?{...p,parentId:'missing'}:p)),h.props,h.cols,h.rows));
assert.throws(()=>importLayout(exportLayout(h.props.map(p=>p.id===laptop.id?{...p,x:0}:p)),h.props,h.cols,h.rows));
console.log('PASS modular surfaces: atomic table movement, constrained child drag, resize/delete/rotation guards and parent validation');
