import assert from 'node:assert/strict';
import {build} from 'esbuild';
const result=await build({stdin:{contents:"export * from './src/editor/model'; export {RATNA_HOUSE} from './src/game/locations/ratnaHouse';",resolveDir:process.cwd(),loader:'ts'},bundle:true,write:false,platform:'node',format:'esm'});
const {moveWithContents,replaceAttachedProp,attachTo,rotateWithContents,resizeProp,rotateProp,addCatalogProp,deleteProp,exportLayout,importLayout,positionProp,exportPositions,importPositions,placementWarnings,RATNA_HOUSE:h}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
const p=h.props.find(p=>p.id==='house-sofa');const original=JSON.stringify(h);
assert.equal(positionProp(p,11.13,18.18,h.cols,h.rows,.25).x,11.25);
assert.equal(positionProp(p,-4,50,h.cols,h.rows,.25).x,0);
assert.equal(positionProp(p,-4,50,h.cols,h.rows,.25).y,h.rows-p.h);
assert.deepEqual(importPositions(exportPositions(h.props),h.props,h.cols,h.rows),h.props);
const bad=JSON.parse(exportPositions(h.props));bad.placements[0]=bad.placements[1];assert.throws(()=>importPositions(JSON.stringify(bad),h.props,h.cols,h.rows));
const outside=JSON.parse(exportPositions(h.props));outside.placements[0].x=1000;assert.throws(()=>importPositions(JSON.stringify(outside),h.props,h.cols,h.rows));
assert.ok(placementWarnings({...p,x:0,y:0},h.props,h.tiles,h.walls).includes('Bertumpuk dengan dinding.'));
const other=h.props.find(q=>q.solid&&q.id!==p.id);assert.ok(placementWarnings({...p,x:other.x,y:other.y},h.props,h.tiles).some(w=>w.includes('furnitur')));
assert.equal(JSON.stringify(h),original);
console.log('PASS editor model: snap, bounds, round trip, duplicate/out-of-bounds rejection, wall/prop warnings, immutable source');

const added=addCatalogProp('sofa','editor-test',12,14,h.cols,h.rows,.25);
const sized=resizeProp(added,3,1.2,h.cols,h.rows);
const rotated=rotateProp(sized,h.cols,h.rows);
assert.deepEqual([rotated.w,rotated.h,rotated.rotation],[1.2,3,90]);
let cycle=sized;for(let i=0;i<4;i++)cycle=rotateProp(cycle,h.cols,h.rows);
assert.deepEqual([cycle.x,cycle.y,cycle.w,cycle.h,cycle.rotation],[sized.x,sized.y,sized.w,sized.h,0]);
const layout=[...h.props,rotated];assert.deepEqual(importLayout(exportLayout(layout),h.props,h.cols,h.rows),layout);
assert.deepEqual(importLayout(exportPositions(h.props),h.props,h.cols,h.rows),h.props);
assert.equal(deleteProp(layout,rotated.id).length,h.props.length);
assert.throws(()=>deleteProp(layout,'house-laptop'));
assert.throws(()=>resizeProp(added,0,1,h.cols,h.rows));
assert.throws(()=>rotateProp(h.props.find(p=>p.deviceId),h.cols,h.rows));
assert.throws(()=>importLayout(exportLayout(layout.filter(p=>p.id!=='house-laptop')),h.props,h.cols,h.rows));
assert.throws(()=>importLayout(exportLayout([...h.props,{...rotated,rotation:45}]),h.props,h.cols,h.rows));
assert.throws(()=>importLayout(exportLayout([...h.props,{...rotated,solid:false}]),h.props,h.cols,h.rows));
assert.throws(()=>importLayout(exportLayout([...h.props,rotated,rotated]),h.props,h.cols,h.rows));
const edge=rotateProp({...added,x:h.cols-added.w,y:h.rows-added.h},h.cols,h.rows);
assert.ok(edge.x>=0&&edge.y>=0&&edge.x+edge.w<=h.cols&&edge.y+edge.h<=h.rows);
assert.equal(JSON.stringify(h),original);
console.log('PASS editor 2: add/delete/resize/rotation cycle, edge bounds, protected devices, v1/v2 round trip and malformed import rejection');
const legacyDecor={id:'house-pkk-board',kind:'pkk-board',x:2,y:9.12,w:1.6,h:.9,solid:false};
assert.deepEqual(importLayout(exportLayout([...h.props,legacyDecor]),h.props,h.cols,h.rows),h.props);
const legacyPositions=JSON.parse(exportPositions(h.props));legacyPositions.placements.push({id:'house-family-photo',x:4,y:7.12});
assert.deepEqual(importPositions(JSON.stringify(legacyPositions),h.props,h.cols,h.rows),h.props);
console.log('PASS retired wall decorations are removed from legacy v1/v2 imports');

const table=h.props.find(p=>p.id==='house-study-table'), laptop=h.props.find(p=>p.id==='house-laptop');
const shifted=moveWithContents(h.props,table.id,table.x+1,table.y+.5,h.cols,h.rows,0);
assert.equal(shifted.find(p=>p.id===laptop.id).x,laptop.x+1);
assert.equal(shifted.find(p=>p.id===laptop.id).y,laptop.y+.5);
assert.throws(()=>deleteProp(h.props,table.id));
assert.throws(()=>rotateWithContents(h.props,table.id,h.cols,h.rows));
assert.throws(()=>replaceAttachedProp(h.props,{...table,w:.8,h:.7}));
assert.throws(()=>attachTo(h.props,laptop.id,undefined));
